# A dictionary in Python is a built-in data type that stores data as key-value pairs. 
# Think of it like a real dictionary, where a word (key) maps to its meaning (value).

student = {
    "name": "Alice",
    "age": 20,
    "grade": "A"
}
print(student)
print(student["name"])
print(student.keys())
print(student.values())